import assert from 'node:assert/strict';
import test from 'node:test';
import {createRequire} from 'node:module';
import {existsSync,mkdtempSync,mkdirSync,readdirSync,writeFileSync,rmSync} from 'node:fs';
import {homedir,tmpdir} from 'node:os';
import {join,dirname} from 'node:path';
import {spawnSync} from 'node:child_process';
const require=createRequire(import.meta.url);
const {gradleArguments}=require('../templates/automation/verification/bounded-execution.cjs');
const files=root=>!existsSync(root)?[]:readdirSync(root,{withFileTypes:true}).flatMap(e=>e.isDirectory()?files(join(root,e.name)):[join(root,e.name)]);
test('real Gradle preserves incremental compiler outputs, executes focused tests, and blocks extra dependent suites',()=>{
 const root=mkdtempSync(join(tmpdir(),'orchestrator-bounded-gradle-'));
 try {
  const gradle=files(join(homedir(),'.gradle/wrapper/dists/gradle-9.4.1-all')).find(p=>p.endsWith('/bin/gradle'));
  assert(gradle,'This integration check requires the existing cached Gradle 9.4.1 distribution');
  const jar=(g,a)=>{const p=files(join(homedir(),'.gradle/caches/modules-2/files-2.1',g,a)).find(p=>p.endsWith('.jar')&&!/-sources|-javadoc/.test(p));assert(p);return p;};
  const put=(p,s)=>{mkdirSync(dirname(join(root,p)),{recursive:true});writeFileSync(join(root,p),s);};
  put('settings.gradle','rootProject.name="bounded-fixture"\ninclude(":app")\n');
  const junit=JSON.stringify(jar('junit','junit')),hamcrest=JSON.stringify(jar('org.hamcrest','hamcrest-core'));
  const build=`plugins { id 'java' }\ndependencies { testImplementation files(${junit}, ${hamcrest}) }\ntasks.withType(Test).configureEach { outputs.upToDateWhen { false }; outputs.doNotCacheIf('fresh scoped results') { true }; useJUnit(); filter { includeTestsMatching 'example.FeatureTest' }; testLogging { events 'passed' } }\ntasks.register('unapprovedTest', Test) { testClassesDirs = sourceSets.test.output.classesDirs; classpath = sourceSets.test.runtimeClasspath }\n`;
  put('app/build.gradle',build);
  put('app/src/main/java/example/Feature.java','package example; public class Feature { public static int value() { return 42; } }');
  put('app/src/test/java/example/FeatureTest.java','package example; public class FeatureTest { @org.junit.Test public void value() { org.junit.Assert.assertEquals(42,Feature.value()); } }');
  const c={targetTests:[{gradleTask:':app:test',filter:'example.FeatureTest'}],verification:{scope:{version:3,mode:'bounded',regressionTests:[],tasks:{assembleTasks:[],lintTasks:[],deviceTestTasks:[]}}}};
  const config={gradleVerification:{fullUnitTestTasks:[':app:test'],assembleTasks:[],lintTasks:[':app:lintRelease'],deviceTestTasks:[]}};
  const run=(task=':app:test')=>spawnSync(gradle,[task,'--offline','--max-workers=2','--no-daemon','--console=plain',...gradleArguments(c,[task],config)],{cwd:root,encoding:'utf8',timeout:120000,maxBuffer:8*1024*1024});
  const first=run();assert.equal(first.status,0,first.stdout+first.stderr);
  const second=run();assert.equal(second.status,0,second.stdout+second.stderr);
  assert.match(second.stdout,/> Task :app:compileJava UP-TO-DATE/);
  assert.match(second.stdout,/> Task :app:compileTestJava UP-TO-DATE/);
  assert.match(second.stdout,/FeatureTest > value PASSED/);
  assert.doesNotMatch(second.stdout,/> Task :app:test (UP-TO-DATE|FROM-CACHE)/);
  c.verification.scope.buildMode='clean';
  const clean=run(':app:clean');assert.equal(clean.status,0,clean.stdout+clean.stderr);
  const cached=run();assert.equal(cached.status,0,cached.stdout+cached.stderr);
  assert.match(cached.stdout,/> Task :app:compileJava FROM-CACHE/);
  assert.match(cached.stdout,/> Task :app:compileTestJava FROM-CACHE/);
  assert.match(cached.stdout,/FeatureTest > value PASSED/);
  c.verification.scope.buildMode='incremental';
  put('app/build.gradle',build+"\ntest.dependsOn(unapprovedTest)\n");
  const blocked=run();assert.notEqual(blocked.status,0);
  assert.match(blocked.stdout+blocked.stderr,/Test task exceeds approved verification scope: :app:unapprovedTest/);
  assert.doesNotMatch(blocked.stdout,/FeatureTest > value PASSED/);
  put('app/build.gradle',build+"\ntasks.register('lintRelease') {}\ntest.dependsOn(lintRelease)\n");
  const lint=run();assert.notEqual(lint.status,0);
  assert.match(lint.stdout+lint.stderr,/Verification task exceeds approved scope: :app:lintRelease/);
  put('app/build.gradle',build+"\ntasks.register('purgeOutputs', Delete) { delete layout.buildDirectory }\ntest.dependsOn(purgeOutputs)\n");
  const purge=run();assert.notEqual(purge.status,0);
  assert.match(purge.stdout+purge.stderr,/Cleanup requires explicit approval: :app:purgeOutputs/);
  console.log('Gradle compiler outputs reused UP-TO-DATE and FROM-CACHE; selected Test actually executed; extra Test, lint and Delete dependencies blocked.');
 } finally { rmSync(root,{recursive:true,force:true}); }
});
